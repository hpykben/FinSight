suppressMessages(library(readxl))
suppressMessages(library(caret))
suppressMessages(library(dplyr))
rawData <- read_excel('Financial_Dataset.xlsx', sheet = 1)
rawData <- rawData %>% mutate(Quarter = as.factor(Quarter), Credit_Risk_Score = as.factor(Credit_Risk_Score), Stock_Trend = as.factor(Stock_Trend))
set.seed(42)
creditRiskModel <- train(Credit_Risk_Score ~ Debt_to_Equity + Current_Ratio + EPS + Revenue + Credit_Score, data = rawData, method = 'rpart', trControl = trainControl(method = 'cv', number = 5), tuneLength = 5, na.action = na.omit)
stockTrendModel <- train(Stock_Trend ~ EPS + Stock_Volatility + Market_Cap, data = rawData, method = 'rpart', trControl = trainControl(method = 'cv', number = 5), tuneLength = 5, na.action = na.omit)
cases <- data.frame(Debt_to_Equity = c(1,6,8), Current_Ratio = c(1.2,0.8,0.3), EPS = c(2,-1,0), Revenue = c(100000,400000,700000), Credit_Score = c(650,500,300))
print('credit probs')
print(predict(creditRiskModel, cases, type = 'prob'))
print('stock probs')
print(predict(stockTrendModel, data.frame(EPS = cases$EPS, Stock_Volatility = cases$Debt_to_Equity * 10, Market_Cap = cases$Revenue / 1000), type = 'prob'))
